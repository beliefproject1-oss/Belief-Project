/* Belief Project — the wilayas and communes of Algeria for the order page's address pickers.

     node tools/prepare-places.js

   Reads _reference/data/algeria-cities.json — the 58 wilayas and their 1,541 communes, in French (Latin letters) and
   Arabic, from the open dataset github.com/othmanus/algeria-cities (json/algeria_cities.json), which follows the
   official administrative division (law of 1984 and the ten wilayas created in 2019) — and writes
   assets/data/places.js: window.BELIEF_PLACES = { wilayas: [[code, French, Arabic]], communes: { code: [[French, Arabic]] } },
   communes in alphabetical order. The script stops if the counts differ from the official 58 and 1,541. */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SOURCE = '_reference/data/algeria-cities.json';
const OUT = 'assets/data/places.js';
const OFFICIAL = { wilayas: 58, communes: 1541 };

const rows = JSON.parse(fs.readFileSync(path.join(ROOT, SOURCE), 'utf8'));
const clean = s => String(s || '').replace(/\s+/g, ' ').trim();
const wilayas = new Map(), communes = {};
for (const r of rows) {
  const code = Number(r.wilaya_code);
  if (!wilayas.has(code)) wilayas.set(code, [code, clean(r.wilaya_name_ascii), clean(r.wilaya_name)]);
  (communes[code] = communes[code] || []).push([clean(r.commune_name_ascii), clean(r.commune_name)]);
}
const total = Object.values(communes).reduce((n, list) => n + list.length, 0);
if (wilayas.size !== OFFICIAL.wilayas || total !== OFFICIAL.communes) {
  throw new Error(`expected ${OFFICIAL.wilayas} wilayas and ${OFFICIAL.communes} communes, found ${wilayas.size} and ${total}`);
}
const fr = new Intl.Collator('fr', { sensitivity: 'base' });
for (const code of Object.keys(communes)) communes[code].sort((a, b) => fr.compare(a[0], b[0]));
const data = { source: 'github.com/othmanus/algeria-cities', wilayas: [...wilayas.values()].sort((a, b) => a[0] - b[0]), communes };
fs.writeFileSync(path.join(ROOT, OUT),
  '/* Generated by tools/prepare-places.js — do not edit by hand. The 58 wilayas of Algeria and their 1,541 communes,\n' +
  '   in French and Arabic. */\nwindow.BELIEF_PLACES = ' + JSON.stringify(data) + ';\n');
console.log(`wrote ${OUT}: ${wilayas.size} wilayas, ${total} communes, ${(fs.statSync(path.join(ROOT, OUT)).size / 1024).toFixed(0)} KB`);
